//! Turns an `Action` into the request to send, reading filter files on the way.
//!
//! May depend on: config, error, input, protocol.

use crate::config::{Action, Filter, GetData, InputSource, Invocation, ReadOptions, Subscription};
use crate::error::Error;
use crate::input;
use crate::protocol::filter::ResolvedFilter;
use crate::protocol::ops::get::Get;
use crate::protocol::ops::get_config::GetConfig;
use crate::protocol::ops::get_data::GetData as GetDataOperation;
use crate::protocol::ops::get_schema::GetSchema;
use crate::protocol::ops::simple::{
    Commit, CopyRunningToStartup, DiscardChanges, KillSession, Validate,
};
use crate::protocol::ops::subscription::{
    CreateSubscription, EstablishSubscription, KillSubscription,
};
use crate::protocol::ops::{
    Operation, ReadParams, Streamed, copy_config, edit_config, edit_data, raw_rpc, rpc,
};

/// The operation for actions that send one generated request; `None` for the others
/// (`Hello`, session scripts, interactive mode, and actions that stream a payload).
pub fn build_operation(action: &Action) -> Result<Option<Box<dyn Operation>>, Error> {
    Ok(match action {
        Action::Get(options) => Some(Box::new(Get(read_params(options)?))),
        Action::GetConfig { db, options } => Some(Box::new(GetConfig {
            source: db.clone(),
            params: read_params(options)?,
        })),
        Action::GetData(options) => Some(Box::new(get_data(options)?)),
        Action::KillSession(id) => Some(Box::new(KillSession(id.clone()))),
        Action::DiscardChanges => Some(Box::new(DiscardChanges)),
        Action::Commit => Some(Box::new(Commit)),
        Action::Validate(db) => Some(Box::new(Validate(db.clone()))),
        Action::CopyRunningToStartup => Some(Box::new(CopyRunningToStartup)),
        Action::GetSchema(identifier) => Some(Box::new(GetSchema(identifier.clone()))),
        Action::CreateSubscription(s) => Some(Box::new(CreateSubscription {
            stream: s.stream.clone(),
            filter: resolve(s.filter.as_ref())?,
            start_time: s.start_time.clone(),
            stop_time: s.stop_time.clone(),
        })),
        Action::EstablishSubscription(s) => Some(Box::new(establish(s)?)),
        Action::KillSubscription(id) => Some(Box::new(KillSubscription(*id))),
        Action::Hello
        | Action::Rpc(_)
        | Action::EditConfig(_)
        | Action::EditData(_)
        | Action::CopyConfig(_)
        | Action::SessionFile(_)
        | Action::Interactive => None,
    })
}

/// For actions that stream a payload from an input into an `<rpc>`: the envelope and the input.
pub fn build_streamed(action: &Action) -> Option<(Streamed, InputSource)> {
    match action {
        Action::Rpc(source) => Some((Streamed::bare(), source.clone())),
        Action::EditConfig(p) => Some((
            edit_config::streamed(&p.db, p.trace_id.as_deref()),
            p.input.clone(),
        )),
        Action::EditData(p) => Some((
            edit_data::streamed(&p.db, p.trace_id.as_deref()),
            p.input.clone(),
        )),
        Action::CopyConfig(p) => Some((
            copy_config::streamed(&p.db, p.trace_id.as_deref()),
            p.input.clone(),
        )),
        _ => None,
    }
}

/// The complete first request of `invocation` with the given message id, as the server would
/// receive it. `None` if the action sends nothing generated by the tool.
pub fn render(invocation: &Invocation, message_id: u32) -> Result<Option<String>, Error> {
    if let Some(operation) = build_operation(&invocation.action)? {
        return Ok(Some(rpc(
            operation.as_ref(),
            message_id,
            &invocation.rpc_attribute,
        )));
    }
    let Some((streamed, source)) = build_streamed(&invocation.action) else {
        return Ok(None);
    };
    let payload = input::read_to_string(&source)?;
    Ok(Some(format!(
        "{}{}{payload}{}{}",
        raw_rpc::start(message_id, &invocation.rpc_attribute),
        streamed.prefix,
        streamed.suffix,
        raw_rpc::END
    )))
}

fn resolve(filter: Option<&Filter>) -> Result<Option<ResolvedFilter>, Error> {
    Ok(match filter {
        None => None,
        Some(Filter::XPath(select)) => Some(ResolvedFilter::XPath(select.clone())),
        Some(Filter::Subtree(source)) => {
            Some(ResolvedFilter::Subtree(input::read_to_string(source)?))
        }
    })
}

fn read_params(options: &ReadOptions) -> Result<ReadParams, Error> {
    Ok(ReadParams {
        filter: resolve(options.filter.as_ref())?,
        with_defaults: options.with_defaults,
        with_inactive: options.with_inactive,
    })
}

fn get_data(options: &GetData) -> Result<GetDataOperation, Error> {
    let subtree = match &options.subtree {
        None => None,
        Some(source) => Some(input::read_to_string(source)?),
    };
    Ok(GetDataOperation {
        db: options.db.clone(),
        xpath: options.xpath.clone(),
        subtree,
        config_filter: options.config_filter,
        max_depth: options.max_depth.clone(),
        with_origin: options.with_origin,
        origin_filter: options.origin_filter.clone(),
        negated_origin_filter: options.negated_origin_filter.clone(),
        with_defaults: options.with_defaults,
        with_inactive: options.with_inactive,
    })
}

fn establish(s: &Subscription) -> Result<EstablishSubscription, Error> {
    Ok(EstablishSubscription {
        stream: s.stream.clone(),
        filter: resolve(s.filter.as_ref())?,
        replay_start_time: s.start_time.clone(),
        stop_time: s.stop_time.clone(),
    })
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::config::{Db, InputSource};
    use crate::protocol::ops::rpc;

    #[test]
    fn only_request_building_actions_have_an_operation() {
        assert!(build_operation(&Action::Hello).unwrap().is_none());
        assert!(build_operation(&Action::Interactive).unwrap().is_none());
        assert!(build_operation(&Action::Commit).unwrap().is_some());
        assert!(
            build_operation(&Action::Get(ReadOptions::default()))
                .unwrap()
                .is_some()
        );
    }

    #[test]
    fn get_config_reads_the_subtree_filter_file() {
        let dir = tempfile::tempdir().unwrap();
        let path = dir.path().join("filter.xml");
        std::fs::write(&path, "<a/>").unwrap();
        let action = Action::GetConfig {
            db: Db::default(),
            options: ReadOptions {
                filter: Some(Filter::Subtree(InputSource::File(path))),
                ..ReadOptions::default()
            },
        };
        let msg = rpc(&*build_operation(&action).unwrap().unwrap(), 1, "");
        assert!(
            msg.contains("<filter type=\"subtree\"><a/></filter>"),
            "{msg}"
        );
    }

    #[test]
    fn a_missing_filter_file_is_an_error() {
        let action = Action::Get(ReadOptions {
            filter: Some(Filter::Subtree(InputSource::File(
                "/no/such/filter.xml".into(),
            ))),
            ..ReadOptions::default()
        });
        assert!(build_operation(&action).is_err());
    }
}
